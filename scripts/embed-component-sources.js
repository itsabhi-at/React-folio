/**
 * Build-time script: reads UI library component sources and generates
 * componentSources.generated.js so the app can show/copy source code.
 * Run via: npm run generate:sources (or automatically before build).
 */
const fs = require("fs");
const path = require("path");

const COMPONENTS_DIR = path.join(
  __dirname,
  "..",
  "src",
  "components",
  "ui-library",
  "components"
);
const OUT_FILE = path.join(
  __dirname,
  "..",
  "src",
  "components",
  "ui-library",
  "componentSources.generated.js"
);

function escapeForTemplateLiteral(str) {
  return str
    .replace(/\\/g, "\\\\")
    .replace(/`/g, "\\`")
    .replace(/\$/g, "\\$");
}

const files = fs.readdirSync(COMPONENTS_DIR).filter((f) => f.endsWith(".js"));
const out = {};

for (const file of files) {
  const key = path.basename(file, ".js");
  const content = fs.readFileSync(path.join(COMPONENTS_DIR, file), "utf8");
  out[key] = escapeForTemplateLiteral(content);
}

const lines = [
  "// Auto-generated by scripts/embed-component-sources.js – do not edit",
  "/* eslint-disable import/no-anonymous-default-export */",
  "export default {",
  ...Object.entries(out).map(
    ([k, v]) => `  ${JSON.stringify(k)}: \`${v}\`,`
  ),
  "};",
];

fs.writeFileSync(OUT_FILE, lines.join("\n"), "utf8");
console.log("Generated", OUT_FILE, "with keys:", Object.keys(out).join(", "));
